hr("IDEA 1. Cold-air Na-X / Li-X with warm-vacuum regeneration and rotary-valve rapid cycling")
# Wilson 2022 (iScience), Na-X at 420 ppm, pre-dried real air, breakthrough, normalised to 420 ppm
T_w = np.array([20, 0, -20, -40, -58]) + 273.15
q_w = np.array([0.30, 0.65, 1.1, 1.9, 2.5])        # mol/kg
# Dual-site Langmuir: site A strong (cation sites), site B weak. Fit dS_A, dS_B, qA with dH fixed from
# Wilson's isosteric heats (44-49 kJ/mol at low loading) and a weaker bulk site; qA+qB = 5.5 mol/kg (13X saturation
# near 1 bar, 25 C is ~4.5-5 mol/kg; Wang & LeVan 2009 give ~5-6 total DSL saturation).
Q_TOT = 5.5
# extra anchors at 25 C from the 13X literature (binderless pellets, dry): ~2.7 mol/kg at 10 kPa and ~4.6 mol/kg at 100 kPa
anchors = [(298.15, 1.0e4, 2.7), (298.15, 1.0e5, 4.6)]
def model(params, T, p=P_CO2_AIR):
    dSA, dSB, qA, dHB = params
    qB = Q_TOT - qA
    return (loading(p, T, -49_000.0, dSA, qA) + loading(p, T, dHB, dSB, qB))
def resid(params):
    r = [(model(params, T) - q) / q for T, q in zip(T_w, q_w)]
    r += [(model(params, T, p) - q) / q for T, p, q in anchors]
    return np.array(r)
fit = least_squares(resid, x0=[-150.0, -120.0, 1.5, -36_000.0],
                    bounds=([-250, -200, 0.3, -45_000], [-60, -60, 4.0, -25_000]))
dSA, dSB, qA, dHB = fit.x
qB = Q_TOT - qA
print(f"  dual-site Langmuir fit to Wilson Na-X points + 25 C anchors: site A dH -49 kJ/mol, dS {dSA:.0f} J/mol/K, q_max {qA:.2f} mol/kg;"
      f" site B dH {dHB/1e3:.0f} kJ/mol, dS {dSB:.0f}, q_max {qB:.2f}")
for T, q in zip(T_w, q_w):
    print(f"    {T-273.15:>5.0f} C, 420 ppm  measured {q:.2f}  model {model(fit.x, T):.2f} mol/kg")
for T, p, q in anchors:
    print(f"    {T-273.15:>5.0f} C, {p/1e3:.0f} kPa   anchor {q:.2f}  model {model(fit.x, T, p):.2f} mol/kg")

def q_dual(p, T):
    return loading(p, T, -49_000.0, dSA, qA) + loading(p, T, dHB, dSB, qB)

des_list = [(25,100.0),(60,300.0),(60,1e3),(80,300.0),(80,1e3),(100,1e3),(120,1e3),(200,1e3)]
print("\n  Working capacity (mol/kg) from adsorption at 420 ppm to desorption at (T_des, p_des), dual-site model:")
print(f"  {'T_ads':>6} | " + " | ".join(f"{t:>3}C/{p/1e3:g}kPa" for t, p in des_list))
cases = {}
for tads in (-40, -30, -20, -10, 0):
    row = []
    for tdes, pdes in des_list:
        wc = q_dual(P_CO2_AIR, tads+273.15) - q_dual(pdes, tdes+273.15)
        cases[(tads, tdes, pdes)] = wc
        row.append(f"{wc:>11.2f}")
    print(f"  {tads:>5}C | " + " | ".join(row))

print("\n  Cycle energy for Na-X (cp 920 J/kg/K, no inert, no heat recovery, no water):")
print(f"  {'T_ads':>6}{'T_des':>7}{'p_des Pa':>10}{'wc mol/kg':>11}{'rxn GJ/t':>10}{'sens GJ/t':>11}{'vac GJ_e/t':>12}{'heat GJ/t':>11}{'work-eq GJ/t':>14}{'2nd law':>9}")
for tads, tdes, pdes in [(-20,60,1e3),(-20,80,1e3),(-20,80,300.0),(-20,100,1e3),(-30,80,1e3),(-40,80,1e3),(-20,200,1e3),(-40,200,1e3)]:
    wc = cases[(tads, tdes, pdes)]
    if wc <= 0.05:
        print(f"  {tads:>5}C{tdes:>6}C{pdes:>10.0f}{wc:>11.2f}   no useful working capacity"); continue
    rxn = 47_000.0
    sens = 920.0 * (tdes - tads) / wc
    T_a = tads + 273.15
    vac = R * T_a * math.log(P0 / pdes) / 0.7
    heat = rxn + sens
    carnot = 1 - T_a / (tdes + 273.15)
    weq = gj_per_tonne(heat * carnot + vac) + FAN100
    floor = gj_per_tonne(min_separation_work(X_AIR, CAP, 0.99, T_a))
    print(f"  {tads:>5}C{tdes:>6}C{pdes:>10.0f}{wc:>11.2f}{gj_per_tonne(rxn):>10.2f}{gj_per_tonne(sens):>11.2f}{gj_per_tonne(vac):>12.2f}"
          f"{gj_per_tonne(heat):>11.2f}{weq:>14.2f}{floor/weq:>9.0%}")

print("\n  Drying penalty at the cold site (all water removed upstream on a desiccant regenerated by zeolite-bed sensible heat):")
for tc, rh in [(-10, 0.7), (-20, 0.7), (-30, 0.7)]:
    T = tc + 273.15
    n = rh * p_sat(T) / P_CO2_AIR / CAP
    print(f"    {tc:>4} C, {rh:.0%} RH: {n:5.2f} mol H2O per mol CO2 captured -> {gj_per_tonne(n*50_000):.2f} GJ/t if regenerated with 50 kJ/mol and no recovery")

print("\n  Productivity and sorbent cost (rapid cycles):")
wc = cases[(-30, 80, 1e3)]
print(f"  (using -30 C adsorption, 80 C / 1 kPa desorption: wc {wc:.2f} mol/kg)")
for cyc_min in (5, 10, 30):
    cpd = 24 * 60 / cyc_min * 0.5    # half of the time adsorbing (2-bed rotary valve)
    print(f"    {cyc_min:>3}-min full cycle: {productivity(wc, cpd):.2f} kg CO2/kg zeolite/day (amine fast-cycle reference ~0.95-1.4)")
for price, years, cyc_min in [(3.0, 15, 10), (3.0, 5, 10), (10.0, 5, 10)]:
    cycles = years * 365 * 24 * 60 / cyc_min * 0.5
    print(f"    ${price}/kg, {years} y life at {cyc_min}-min cycles ({cycles:,.0f} cycles): ${sorbent_cost_per_tonne(price, wc, cycles):.2f}/t")
# air-supply-limited adsorption time for a laminate: kg sorbent per m2 face / (air flux * CO2 * capture)
for areal in (5.0, 10.0):
    mol_per_s_m2 = 2.0 / (R * 243.15 / P0) * X_AIR * CAP   # m3/s/m2 -> mol CO2/s/m2 at 2 m/s face velocity, -30 C
    t_ads = areal * wc / mol_per_s_m2 / 60
    print(f"    laminate {areal:.0f} kg/m2 face, 2 m/s, 75% capture: air-supply-limited adsorption time {t_ads:.1f} min to load {wc:.2f} mol/kg")
print("  Note: single-site Langmuir in sorbent.py predicted 0.85 mol/kg for -20 C -> 60 C/1 kPa; the dual-site fit is the quantity to test.")

