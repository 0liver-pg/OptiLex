CAP = 0.75
FAN100 = fan_work_gj_per_tonne(X_AIR, CAP, 100.0)

def p_sat(T):
    if T < 273.15:
        return math.exp(9.550426 - 5723.265 / T + 3.53068 * math.log(T) - 0.00728332 * T)
    tc = T - 273.15
    return 610.94 * math.exp(17.625 * tc / (tc + 243.04))

