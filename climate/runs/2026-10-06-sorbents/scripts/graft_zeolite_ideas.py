hr("IDEA 5. Salt-in-porous-matrix K2CO3/KHCO3 (desiccant-composite graft) with thermal regeneration")
# Thermodynamics of 2 KHCO3(s) -> K2CO3(s) + CO2 + H2O(g), NIST/CRC formation data
dHf = {"KHCO3": -963.2, "K2CO3": -1151.0, "CO2": -393.5, "H2O_g": -241.8, "K2CO3.1.5H2O": -1609.0}  # kJ/mol (sesquihydrate approx.)
S = {"KHCO3": 115.5, "K2CO3": 155.5, "CO2": 213.8, "H2O_g": 188.8}
dH = dHf["K2CO3"] + dHf["CO2"] + dHf["H2O_g"] - 2 * dHf["KHCO3"]
dS = S["K2CO3"] + S["CO2"] + S["H2O_g"] - 2 * S["KHCO3"]
print(f"  2KHCO3 -> K2CO3 + CO2 + H2O(g): dH {dH:.1f} kJ/mol CO2 ({gj_per_tonne(dH*1e3):.2f} GJ/t), dS {dS:.1f} J/mol/K, T(dG=0 at 1 bar each) {dH*1e3/dS-273.15:.0f} C")
for tc, rh in [(25, 0.5), (25, 0.8), (35, 0.6), (5, 0.7)]:
    T = tc + 273.15
    pw = rh * p_sat(T) / 1e5
    dG = dH * 1e3 - T * dS + R * T * math.log(P_CO2_AIR / 1e5 * pw)
    pco2_eq = math.exp((-(dH*1e3 - T*dS)) / (R*T)) / pw * 1e5
    print(f"    {tc:>3} C, {rh:.0%} RH: decomposition dG at 420 ppm = {dG/1e3:+.1f} kJ/mol (capture driving force {-dG/1e3:.1f}); "
          f"equilibrium CO2 over KHCO3/K2CO3 = {pco2_eq:.2f} Pa (air 42.6 Pa)")
# regeneration: what CO2 pressure at what temperature? p_CO2*p_H2O = K(T). With steam at 1 bar (p_H2O=1), p_CO2 at:
for tc in (100, 120, 130, 140, 150):
    T = tc + 273.15
    K = math.exp(-(dH*1e3 - T*dS)/(R*T))
    print(f"    {tc} C: p_CO2 * p_H2O = {K:.3f} bar^2 -> at p_H2O 0.3 bar, p_CO2 {K/0.3*1e5/1e3:7.2f} kPa; at p_H2O 1 bar, {K*1e5/1e3:6.2f} kPa")
# cycle heat: reaction 140 kJ/mol (already includes 1 H2O); plus film water; plus sensible (cp ~1,000 J/kg/K composite)
for loading_mol_kg, film_water, tdes in [(1.0, 3.0, 130), (1.5, 3.0, 130), (2.0, 2.0, 130), (1.0, 6.0, 150)]:
    sens = 1000.0 * (tdes - 25) / loading_mol_kg
    heat = dH * 1e3 + film_water * DH_VAP_WATER + sens
    carnot = 1 - 298.15 / (tdes + 273.15)
    print(f"    {loading_mol_kg:.1f} mol/kg, {film_water:.0f} film H2O per CO2, {tdes} C: heat {gj_per_tonne(heat):5.2f} GJ/t "
          f"(rxn {gj_per_tonne(dH*1e3):.2f} + water {gj_per_tonne(film_water*DH_VAP_WATER):.2f} + sens {gj_per_tonne(sens):.2f}); work-eq {gj_per_tonne(heat*carnot)+FAN100:.2f} GJ/t")
# salt loading needed: 1 mol CO2/kg = 1 mol K2CO3/kg = 138 g/kg = 13.8 wt%; SWS rule: pore volume must hold the saturated solution
for wt in (0.15, 0.30, 0.40):
    mol = wt / 0.1382
    # saturated K2CO3 solution at 25 C: 112 g per 100 g water -> 1.9 g solution per g salt, density 1.55 -> 1.22 cm3 per g salt
    v_sol = wt * 1.22   # cm3 per g composite
    print(f"    {wt:.0%} K2CO3: theoretical {mol:.2f} mol CO2/kg; saturated-solution volume {v_sol:.2f} cm3/g composite (support pore volume must exceed this: carbon/silica 0.5-1.5 cm3/g)")
print(f"  sorbent cost at $2/kg, 1.0 mol/kg: {sorbent_cost_per_tonne(2.0, 1.0, 2000):.1f} $/t at 2,000 cycles; {sorbent_cost_per_tonne(2.0, 1.0, 20000):.2f} at 20,000")

