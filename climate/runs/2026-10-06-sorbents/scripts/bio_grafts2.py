print("\n=== CCM liquid loop: can a carbonate contactor hold enough bicarbonate at 420 ppm to release with 1 e-/CO2? (ionic-strength corrected)")
# apparent constants in ~2 M K2CO3 (I ~ 6 M): pK1' ~ 6.0, pK2' ~ 9.7 (Pitzer-type estimates), Henry salted out to ~0.017 M/atm; 25 C
cases = {"ideal 25 C": (10**-6.35, 10**-10.33, 0.034), "2 M K2CO3, 25 C (pK1' 6.0, pK2' 9.7, H 0.017)": (1e-6, 10**-9.7, 0.017),
         "2 M K2CO3, 5 C (pK1' 6.2, pK2' 9.9, H 0.03)": (10**-6.2, 10**-9.9, 0.03)}
for lab, (K1, K2, H) in cases.items():
    Ctot = 2.0
    def pco2(x):
        hco3, co3 = 2*x*Ctot, (1-x)*Ctot
        return (hco3**2 / co3) * K2 / K1 / H
    for frac in (0.25, 0.7):
        x = brentq(lambda x: pco2(x) - frac*420e-6, 1e-7, 0.9999)
        print(f"  {lab}: p_eq = {frac} x ambient at carbonate->bicarbonate conversion {x:.3f}; bicarbonate fraction of carbon {2*x/(1+x):.2f}")
print("  -> bicarbonate never exceeds ~10-20% of dissolved carbon at 420 ppm, so release still needs ~2 H+ per CO2; floor for 2 charges over a 4-unit pH gap:",
      f"{2*4*0.0592*FARADAY/1e3:.0f} kJ/mol = {GJ(2*4*0.0592*FARADAY):.2f} GJ/t (hydroxide loop, dpH 7: {GJ(2*7*0.0592*FARADAY):.2f} GJ/t). "
      "CA only buys the pH-gap term (~0.8 GJ/t at the floor), not the 1-electron prize. Ucaneo-type claims should be checked against this.")

